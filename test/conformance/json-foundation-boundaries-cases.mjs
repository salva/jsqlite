import assert from 'node:assert/strict';
import test from 'node:test';
import {openFixture} from './public-api-adapter.mjs';
import {startFixtureServer} from './fixture-server.mjs';

// SQLite 3.53.4 source ID bf7c7f30031888f4e796e429ab3978879485813aaca6f641c7b33e4e09459bcc.
// src/json.c:jsonbPayloadSize, jsonTranslateTextToBlob, jsonbValidityCheck,
// jsonTranslateBlobToText. Native comparison and exact input: research evidence.
const header=(type,n)=>n<=11?[n*16+type]:n<=255?[0xc0+type,n]:n<=65535?[0xd0+type,n>>8,n&255]:[0xe0+type,n>>>24,(n>>>16)&255,(n>>>8)&255,n&255];
// Preserve identical generated bytes without boxed spread arrays at every level.
const nested=n=>{let b=Uint8Array.of(0);for(let i=0;i<n;i++){const h=header(11,b.length),next=new Uint8Array(h.length+b.length);next.set(h);next.set(b,h.length);b=next}return b};
const malformed=e=>e.kind==='sqlite'&&e.message==='malformed JSON';
// Each group keeps its full original input tuples and lifecycle assertions.
export function registerJsonFoundationBoundaries(enc,group){
 test(`JSON ${group} boundaries ${enc}`,async()=>{
 const bridge=await startFixtureServer(new URL('../fixtures',import.meta.url).pathname);let db;
 try{
  db=await openFixture(new Request(`http://127.0.0.1:${bridge.port}/fixture/${bridge.token}/encoding-${enc}`));
  if(group==='headers'){
  for(const n of [11,12,255,256,65535,65536]){
   const bytes=Uint8Array.from([...header(7,n),...new Uint8Array(n).fill(97)]),text='"'+'a'.repeat(n)+'"';
   const s=db.prepare('SELECT jsonb(?1) AS b,json(?2) AS t,json_valid(?2,8) AS v').statement;
   let saved;
   try{s.bind(1,text);s.bind(2,bytes);
    assert.equal(await s.step(),'row');assert.deepEqual([0,1,2].map(i=>s.columnType(i)),['blob','text','integer']);
    assert.deepEqual([0,1,2].map(i=>s.columnMetadata(i).name),['b','t','v']);
    saved=s.column(0);assert.deepEqual(saved,bytes);assert.equal(s.column(1),text);assert.equal(s.column(2),1n);
    s.reset();assert.equal(await s.step(),'row');assert.deepEqual(s.column(0),bytes);
   }finally{s.finalize()}
   assert.deepEqual(saved,bytes); // public copy survives reset/finalize
  }
  }else if(group==='array'||group==='object'){
  // Both container productions, empty terminal containers, and scalar leaves.
  for(const [open,close] of [group==='array'?['[',']']:['{"a":','}']])for(const leaf of ['0','null','"x"','[]','{}'])for(const depth of [1000,1001]){
   const count=depth-(leaf==='[]'||leaf==='{}'?1:0),text=open.repeat(count)+leaf+close.repeat(count);
   const s=db.prepare('SELECT json_valid(?1) AS valid').statement;
   try{s.bind(1,text);assert.equal(await s.step(),'row');assert.equal(s.columnType(0),'integer');assert.equal(s.column(0),depth===1000?1n:0n)}finally{s.finalize()}
   const render=db.prepare('SELECT json(?1) AS rendered').statement;
   try{render.bind(1,text);if(depth===1000){assert.equal(await render.step(),'row');const saved=render.column(0);assert.equal(saved,text);render.reset();assert.equal(await render.step(),'row');assert.equal(render.column(0),saved)}else{await assert.rejects(render.step(),malformed);assert.throws(()=>render.reset(),malformed)}}finally{render.finalize()}
  }
  }else if(group==='binary'){
  for(const depth of [1000,1001]){
   const bytes=nested(depth),valid=db.prepare('SELECT json_valid(?1,8)').statement;
   try{valid.bind(1,bytes);assert.equal(await valid.step(),'row');assert.equal(valid.column(0),0n)}finally{valid.finalize()}
   const s=db.prepare('SELECT json(?1)').statement;
   try{s.bind(1,bytes);if(depth===1000){assert.equal(await s.step(),'row');assert.equal(s.column(0),'['.repeat(depth)+'null'+']'.repeat(depth))}else{const tooDeep=e=>e.kind==='sqlite'&&e.code===1&&e.message==='JSON nested too deep';await assert.rejects(s.step(),tooDeep);assert.throws(()=>s.reset(),tooDeep)}}finally{s.finalize()}
  }
  }else throw new Error(`Unknown boundary group ${group}`);
  const recovery=db.prepare('SELECT 1').statement;try{assert.equal(await recovery.step(),'row');assert.equal(recovery.column(0),1n)}finally{recovery.finalize()}
 }finally{db?.closeDeferred();await new Promise(r=>bridge.server.close(r))}
 });
}
